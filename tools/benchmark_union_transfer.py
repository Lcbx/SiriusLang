#!/usr/bin/env python3
"""Measure last-use union payload transfer on compiler-generated Sirius C.

The 'transfer' binary is an *experimental C rewrite*, not generated by the
production optimizer. It changes only the adjacent retain/store/release
sequence for freshly constructed payload records. It neither fuses heap
allocations nor changes the general tagged-union layout.
"""
import argparse
import re
import statistics
import subprocess
import tempfile
import time
from pathlib import Path

from build_support import link_flags, require_cc
from project_paths import ROOT, executable_path


# A precise subset of the C emitted for record -> union -> release(record).
# Requiring the adjacent release avoids changing independently-owned records.
TRANSFER = re.compile(
    r'(?P<assign>\t\tvariant->fields\[1\]\.record = )'
    r's_mir_record_retain\((?P<src>r\d+)\);\n'
    r'(?P<store>\s*s_mir_record_store\(&r\d+, variant\);\n\t\}\n)'
    r'\ts_mir_record_release\((?P=src)\); (?P=src) = NULL;'
)


def source(count: int, managed: bool) -> str:
    large = 'rec Large(value: i64, name: string)' if managed else 'rec Large(value: i64, extra: i64)'
    arg = '"hello"' if managed else 'i + 1'
    return f'''rec Small(value: i64)
{large}
let Variant = Small | Large

def main() -> i64
\tvar data = Array[Variant]()
\tfor i in 0..{count}
\t\tif i % 2 == 0
\t\t\tdata = data.append(Small(i))
\t\telse
\t\t\tdata = data.append(Large(i, {arg}))
\tvar total = 0
\tfor item in data
\t\tmatch item
\t\t\tSmall(value)
\t\t\t\ttotal += value
\t\t\tLarge(value, extra)
\t\t\t\ttotal += value
\treturn total % 251
'''


def run_checked(command: list[str], *, expected: int | None = None) -> bytes:
    result = subprocess.run(command, capture_output=True)
    if expected is None and result.returncode != 0:
        raise RuntimeError(f'{command}: code={result.returncode}\n{result.stdout.decode(errors="replace")}\n{result.stderr.decode(errors="replace")}')
    if expected is not None and (result.returncode != expected or result.stdout or result.stderr):
        raise AssertionError(f'{command}: code={result.returncode}, stdout={result.stdout!r}, stderr={result.stderr!r}, expected {expected}')
    return result.stdout


def build(cc: str, source_c: Path, destination: Path, audit: bool) -> None:
    flags = ['-std=c11', '-O2', '-w']
    if audit:
        flags += ['-DSIRIUS_ARC_AUDIT']
    run_checked([cc, *flags, '-I', str(ROOT / 'runtime'), str(source_c),
                 str(ROOT / 'runtime/sirius_runtime.c'), *link_flags(cc), '-o', str(destination)])


def benchmark(compiler: Path, cc: str, count: int, runs: int, managed: bool) -> None:
    label = 'managed string' if managed else 'scalar fields'
    with tempfile.TemporaryDirectory(prefix='sirius-union-transfer-') as temp:
        directory = Path(temp)
        sirius = directory / 'benchmark.sirius'
        baseline_c, transfer_c = directory / 'baseline.c', directory / 'transfer.c'
        sirius.write_text(source(count, managed), encoding='utf-8')
        run_checked([str(compiler), str(sirius), str(baseline_c)])
        base = baseline_c.read_text(encoding='utf-8')
        adjusted, changed = TRANSFER.subn(lambda match: match['assign'] + match['src'] + ';\n' + match['store'] + '\t' + match['src'] + ' = NULL;', base)
        if changed != 2:
            raise AssertionError(f'{label}: expected exactly two constructor transfer sites; found {changed}')
        transfer_c.write_text(adjusted, encoding='utf-8')
        expected = (count * (count - 1) // 2) % 251
        # ARC auditing checks the transformed ownership path with a small
        # workload. A large ARC shadow graph makes the audit itself dominate.
        audit_count = min(count, 256)
        audit_source = directory / 'audit.sirius'
        audit_c = directory / 'audit_baseline.c'
        audit_transfer_c = directory / 'audit_transfer.c'
        audit_source.write_text(source(audit_count, managed), encoding='utf-8')
        run_checked([str(compiler), str(audit_source), str(audit_c)])
        audit_adjusted, audit_changed = TRANSFER.subn(lambda match: match['assign'] + match['src'] + ';\n' + match['store'] + '\t' + match['src'] + ' = NULL;', audit_c.read_text(encoding='utf-8'))
        if audit_changed != 2:
            raise AssertionError(f'{label}: ARC fixture did not match both constructor sites')
        audit_transfer_c.write_text(audit_adjusted, encoding='utf-8')
        audit_expected = (audit_count * (audit_count - 1) // 2) % 251
        for variant, path in (('baseline', audit_c), ('transfer', audit_transfer_c)):
            audit_binary = executable_path(directory / (variant + '_audit'))
            build(cc, path, audit_binary, audit=True)
            run_checked([str(audit_binary)], expected=audit_expected)
        binaries = []
        for variant, path in (('baseline', baseline_c), ('transfer', transfer_c)):
            binary = executable_path(directory / variant)
            build(cc, path, binary, audit=False)
            binaries.append(binary)
        samples: list[list[float]] = [[], []]
        for iteration in range(runs + 2):
            for index in (iteration % 2, (iteration + 1) % 2):
                start = time.perf_counter()
                run_checked([str(binaries[index])], expected=expected)
                elapsed = time.perf_counter() - start
                if iteration >= 2:
                    samples[index].append(elapsed)
        a, b = (statistics.median(samples[0]), statistics.median(samples[1]))
        print(f'{label}: {changed} transfer sites, ARC audit PASS, expected exit {expected}')
        print(f'  baseline {a * 1000:.3f} ms, transferred {b * 1000:.3f} ms; ratio {b / a:.3f}x ({runs} runs)')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--compiler', type=Path, default=ROOT / 'compiler')
    parser.add_argument('--cc', default=require_cc())
    parser.add_argument('--count', type=int, default=160000)
    parser.add_argument('--runs', type=int, default=9)
    args = parser.parse_args()
    if args.count < 2 or args.count % 2 or args.runs < 3:
        parser.error('count must be positive and even; runs must be >= 3')
    compiler = args.compiler.resolve()
    for managed in (False, True):
        benchmark(compiler, args.cc, args.count, args.runs, managed)
    print('Timing includes native startup/execution, but not Sirius compilation or C compilation.')
    print('Experimental rewrite reduces ARC retain/release calls; allocations remain unchanged.')


if __name__ == '__main__':
    main()
